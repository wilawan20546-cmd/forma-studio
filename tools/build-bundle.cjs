'use strict';

const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const sources = ['concepts', 'art-direction', 'holidays', 'exporter', 'vectorizer', 'sharing', 'concept-images', 'app', 'vector-ui'];
const source = sources.map(name => {
  const code = fs.readFileSync(path.join(root, 'js', name + '.js'), 'utf8');
  return '// js/' + name + '.js\n' + code.replace(/^'use strict';\s*/, '').trimEnd();
}).join('\n\n');

const bundle = `// Generated by tools/build-bundle.cjs.
(function () {
  'use strict';

  function boot() {
${source}

    startStudio();
    document.querySelector('#startup-note').hidden = true;
  }

  function start() {
    try {
      boot();
    } catch (error) {
      document.querySelector('#startup-note').textContent =
        'เริ่ม Forma Studio ไม่สำเร็จ กรุณาโหลดหน้าใหม่ หากยังพบปัญหาให้ตรวจข้อความใน Console';
      console.error('Forma Studio startup failed', error);
    }
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', start, {once:true});
  } else {
    start();
  }
})();
`;
fs.writeFileSync(path.join(root, 'forma-studio-v3.0.js'), bundle);
